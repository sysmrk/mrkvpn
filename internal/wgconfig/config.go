// Package wgconfig validates and renders a Linux wg-quick gateway file.
// It does not install networking rules or start WireGuard.
package wgconfig

import (
	"encoding/base64"
	"errors"
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var interfaceName = regexp.MustCompile(`^[a-zA-Z0-9_-]{1,15}$`)
var peerName = regexp.MustCompile(`^[a-zA-Z0-9._-]{1,64}$`)

// Gateway is a deliberately narrow, IPv4-only alpha configuration.
type Gateway struct {
	InterfaceName  string `json:"interface_name"`
	Address        string `json:"address"` // e.g. 10.77.0.1/24
	ListenPort     int    `json:"listen_port"`
	PrivateKeyFile string `json:"private_key_file"`
	Peers          []Peer `json:"peers"`
}

// Peer contains no client private key. WireGuard enforces per-peer source IP
// restrictions through AllowedIPs when these settings are installed.
type Peer struct {
	Name      string `json:"name"`
	PublicKey string `json:"public_key"`
	Address   string `json:"address"` // e.g. 10.77.0.2/32
}

type validated struct {
	address netip.Prefix
	peerIPs []netip.Prefix
	private string
}

func checkKey(key string) bool {
	decoded, err := base64.StdEncoding.Strict().DecodeString(key)
	return err == nil && len(decoded) == 32
}

// Validate checks all configuration and reads the private key from a
// separately protected regular file. Error messages never include key data.
func Validate(c Gateway) error {
	_, err := validate(c)
	return err
}

func validate(c Gateway) (validated, error) {
	var v validated
	if !interfaceName.MatchString(c.InterfaceName) {
		return v, errors.New("invalid interface name")
	}
	if c.ListenPort < 1 || c.ListenPort > 65535 {
		return v, errors.New("listen_port must be 1..65535")
	}
	server, err := netip.ParsePrefix(c.Address)
	if err != nil || !server.Addr().Is4() || !server.Addr().IsPrivate() || server.Bits() < 16 || server.Bits() > 30 {
		return v, errors.New("address must be a private IPv4 interface address with prefix /16 through /30")
	}
	network := server.Masked()
	if isNetworkOrBroadcast(server.Addr(), network) {
		return v, errors.New("server address cannot be network or broadcast address")
	}
	v.address = server

	if !filepath.IsAbs(c.PrivateKeyFile) {
		return v, errors.New("private_key_file must be an absolute path")
	}
	fi, err := os.Lstat(c.PrivateKeyFile)
	if err != nil {
		return v, fmt.Errorf("cannot inspect private_key_file: %w", err)
	}
	if !fi.Mode().IsRegular() || fi.Mode().Perm()&0077 != 0 {
		return v, errors.New("private_key_file must be a regular file with no group/other permissions (e.g. 0600)")
	}
	raw, err := os.ReadFile(c.PrivateKeyFile)
	if err != nil {
		return v, fmt.Errorf("cannot read private_key_file: %w", err)
	}
	v.private = strings.TrimSpace(string(raw))
	if !checkKey(v.private) {
		return v, errors.New("private_key_file does not contain a 32-byte base64 WireGuard key")
	}

	names := map[string]bool{}
	keys := map[string]bool{}
	ips := map[netip.Addr]bool{}
	v.peerIPs = make([]netip.Prefix, 0, len(c.Peers))
	for i, p := range c.Peers {
		if !peerName.MatchString(p.Name) || names[p.Name] {
			return validated{}, fmt.Errorf("peer %d: invalid or duplicate name", i)
		}
		names[p.Name] = true
		if !checkKey(p.PublicKey) || keys[p.PublicKey] || p.PublicKey == publicKeyUnavailableSentinel {
			return validated{}, fmt.Errorf("peer %d: invalid or duplicate public key", i)
		}
		keys[p.PublicKey] = true
		addr, err := netip.ParsePrefix(p.Address)
		if err != nil || !addr.Addr().Is4() || addr.Bits() != 32 || !network.Contains(addr.Addr()) || addr.Addr() == server.Addr() || isNetworkOrBroadcast(addr.Addr(), network) || ips[addr.Addr()] {
			return validated{}, fmt.Errorf("peer %d: address must be a unique host /32 within gateway subnet", i)
		}
		ips[addr.Addr()] = true
		v.peerIPs = append(v.peerIPs, addr)
	}
	return v, nil
}

// Kept so the key validation check is explicit; real public keys cannot be
// inferred from a placeholder or configuration omission.
const publicKeyUnavailableSentinel = ""

// isNetworkOrBroadcast is limited to the IPv4 /16../30 scope validated above.
func isNetworkOrBroadcast(ip netip.Addr, subnet netip.Prefix) bool {
	if ip == subnet.Masked().Addr() {
		return true
	}
	a := subnet.Masked().Addr().As4()
	maskBits := 32 - subnet.Bits()
	broadcast := a
	for bit := 0; bit < maskBits; bit++ {
		broadcast[3-bit/8] |= 1 << uint(bit%8)
	}
	return ip == netip.AddrFrom4(broadcast)
}

// Render emits wg-quick configuration only; it never applies system changes.
// The returned bytes contain the gateway private key and MUST be treated as a
// secret, written to a mode 0600 file and never logged.
func Render(c Gateway) ([]byte, error) {
	v, err := validate(c)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Generated by mrkvpn. Contains a private key. Keep permissions 0600.\n")
	fmt.Fprintf(&b, "[Interface]\nAddress = %s\nListenPort = %d\nPrivateKey = %s\nSaveConfig = false\n", v.address, c.ListenPort, v.private)
	for i, p := range c.Peers {
		fmt.Fprintf(&b, "\n# Device: %s\n[Peer]\nPublicKey = %s\nAllowedIPs = %s\n", p.Name, p.PublicKey, v.peerIPs[i])
	}
	return []byte(b.String()), nil
}

// WriteNew never overwrites existing files (including symlinks) and writes
// secret material with restrictive permissions. It is not an installer.
func WriteNew(path string, content []byte) error {
	if path == "" {
		return errors.New("output path required")
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return fmt.Errorf("cannot create output: %w", err)
	}
	ok := false
	defer func() {
		if !ok {
			_ = os.Remove(path)
		}
	}()
	if _, err := f.Write(content); err != nil {
		_ = f.Close()
		return fmt.Errorf("cannot write output: %w", err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return fmt.Errorf("cannot sync output: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("cannot close output: %w", err)
	}
	ok = true
	return nil
}
